const completeSamplesMigrationKey = 'closetvibe-samples-complete-001-068-v1';
function migrateCompleteSamples(items) {
  try {
    if (localStorage.getItem(completeSamplesMigrationKey) === 'done') return items;
    const ids = new Set(items.map(item => item.id));
    const missing = completeSampleItems.filter(item => !ids.has(item.id));
    const updated = missing.length ? [...items, ...missing.map(item => ({ ...item, occasions: [...item.occasions], weather: [...item.weather] }))] : items;
    if (missing.length && !saveItems(updated)) return items;
    try { localStorage.setItem(completeSamplesMigrationKey, 'done'); }
    catch (error) { console.warn('No se pudo marcar la ampliación del catálogo.', error); }
    return updated;
  } catch (error) {
    console.warn('No se pudo ampliar el catálogo de muestra.', error);
    return items;
  }
}
